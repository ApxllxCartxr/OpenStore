def check_quote_identities(q: dict[str, Any], name: str) -> None:
    """§16.11 step 8, asserted so a typo in the literals above cannot ship.

    An Add-on folds into its parent's `line_total_minor` and is never a Quote
    Line of its own, so the subtotal identity is over `line_total_minor`.
    """
    subtotal = sum(ln["line_total_minor"] for ln in q["lines"])
    assert subtotal == q["subtotal_minor"], f"{name}: subtotal {subtotal} != {q['subtotal_minor']}"

    for ln in q["lines"]:
        folded = ln["qty"] * ln["unit_price_minor"] + sum(a["amount_minor"] for a in ln["addons"])
        assert folded == ln["line_total_minor"], f"{name}: line {ln['sku']} does not fold"

    discounts = sum(d["amount_minor"] for d in q["discount_lines"])
    assert discounts <= 0, f"{name}: a discount must be negative, sign is intrinsic"

    total = subtotal + q["fulfillment_chosen"]["cost_minor"] + discounts + q["round_off_minor"]
    assert total == q["total_minor"], f"{name}: total {total} != {q['total_minor']}"

    assert q["round_off_minor"] == 0, f"{name}: round_off is always 0 in v1 (§16.11 step 7)"

    # Tax is inclusive, so it is reported and never added. Every line's rate must
    # extract to the tax the Quote claims for it, by exact decimal arithmetic.
    assert q["tax_inclusive"] is True, f"{name}: the seeded Merchant is tax-inclusive"
    claimed = sum(t["amount_minor"] for t in q["tax_lines"])
    assert all(
        t["informational"] for t in q["tax_lines"]
    ), f"{name}: inclusive tax is informational"
    assert claimed < q["total_minor"], f"{name}: tax cannot exceed the total it sits inside"


def extract_tax(inclusive_minor: int, rate_bp: int) -> int:
    """§16.11 step 5, exact decimal, never binary float."""
    value = Decimal(inclusive_minor) * Decimal(rate_bp) / Decimal(10000 + rate_bp)
    return int(value.quantize(Decimal("1"), rounding=ROUND_HALF_UP))


def main() -> int:
    vectors = []
    for case in CASES:
        check_quote_identities(case["quote"], case["name"])
        qh = quote_hash(case["quote"])
        dh = pii_commit(TEST_SALT, case["destination"])
        ch = pii_commit(TEST_SALT, CONTACT)
        vectors.append(
            {
                "name": case["name"],
                "note": case["note"],
                "inputs": {
                    "lines": case["lines"],
                    "quote": case["quote"],
                    "destination": case["destination"],
                    "contact": CONTACT,
                    "order_salt_hex": TEST_SALT.hex(),
                    "fulfillment_option_id": case["fulfillment_option_id"],
                    "merchant_domain": MERCHANT_DOMAIN,
                    "expiry_utc": EXPIRY_UTC,
                },
                "expected": {
                    "quote_hash": qh,
                    "destination_hash": dh,
                    "contact_hash": ch,
                    "cart_hash": cart_hash(
                        lines=case["lines"],
                        quote_hash_hex=qh,
                        destination_hash=dh,
                        contact_hash=ch,
                        fulfillment_option_id=case["fulfillment_option_id"],
                        total_minor=case["quote"]["total_minor"],
                        currency=case["quote"]["currency"],
                        merchant_domain=MERCHANT_DOMAIN,
                        expiry_utc=EXPIRY_UTC,
                    ),
                },
            }
        )

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps({"vectors": vectors}, indent=2, ensure_ascii=False) + "\n")
    print(f"wrote {OUT} — {len(vectors)} vectors")
    for v in vectors:
        print(f"  {v['name']:<14} cart_hash {v['expected']['cart_hash']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
