def _line(
    sku: str,
    qty: int,
    unit: int,
    total: int,
    hsn: str,
    rate_bp: int,
    pos: str,
    addons: list[dict[str, Any]] | None = None,
) -> dict[str, Any]:
    return {
        "sku": sku,
        "qty": qty,
        "unit_price_minor": unit,
        "line_total_minor": total,
        "hsn_sac": hsn,
        "gst_rate_bp": rate_bp,
        "place_of_supply": pos,
        "addons": addons or [],
    }


def _tax(kind: str, label: str, rate_bp: int, amount: int) -> dict[str, Any]:
    # Everything seeded is tax-inclusive (§16.11), so every tax line is
    # informational and is never added to the total — it reports what is
    # already inside it. Getting this backwards double-charges every order.
    return {
        "kind": kind,
        "label": label,
        "rate_bp": rate_bp,
        "amount_minor": amount,
        "informational": True,
    }


